// Export the icon names for use in IconPicker
export const AVAILABLE_ICON_NAMES = Object.keys(ICON_MAP);

interface DynamicIconProps {
  name: string;
  size?: number | string;
  stroke?: number;
  className?: string;
  style?: React.CSSProperties;
}

/**
 * DynamicIcon renders a Tabler icon by name.
 * Uses a curated icon map instead of importing all icons to reduce memory usage.
 * Standard format for icons is "IconRocket", "IconSettings", etc.
 */
export const DynamicIcon = memo(function DynamicIcon({
  name,
  size = 24,
  stroke = 2,
  className = "",
  style = {},
}: DynamicIconProps) {
  if (!name) return null;

  // Look up icon in our curated map
  const IconComponent = ICON_MAP[name];

  if (IconComponent) {
    return (
      <IconComponent
        size={size}
        stroke={stroke}
        className={className}
        style={style}
      />
    );
  }

  // Fallback to IconSparkles if icon not found in map
  return (
    <IconSparkles
      size={size}
      stroke={stroke}
      className={className}
      style={style}
    />
  );
});
